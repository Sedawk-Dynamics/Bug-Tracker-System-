import fs from 'node:fs';
import {readSettings} from './settings.mjs';
const s=readSettings(true);
if(!/^[a-f0-9]{32}$/i.test(s.accountId||''))throw new Error('Set your Cloudflare accountId.');
if(!/^[a-f0-9-]{36}$/i.test(s.databaseId||'') || s.databaseId==='00000000-0000-4000-8000-000000000000')throw new Error('Set your real D1 databaseId.');
if(!/^[a-z0-9][a-z0-9-]*$/.test(s.workerName||'') || !s.databaseName)throw new Error('Set workerName and databaseName.');
if(!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(s.ownerEmail||''))throw new Error('Set ownerEmail.');
const generated=JSON.parse(fs.readFileSync('dist/server/wrangler.json','utf8'));
const config={...generated,name:s.workerName,account_id:s.accountId,main:'../dist/server/index.js',assets:{directory:'../dist/client'},vars:{...generated.vars,OWNER_EMAIL:s.ownerEmail.trim().toLowerCase()},workers_dev:true,preview_urls:false,d1_databases:[{binding:'DB',database_name:s.databaseName,database_id:s.databaseId}]};
delete config.topLevelName;delete config.build;delete config.services;
fs.writeFileSync('cloudflare/wrangler.json',JSON.stringify(config,null,2));
console.log('Prepared deployment configuration for '+s.workerName);
